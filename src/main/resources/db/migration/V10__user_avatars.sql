--
-- A nullable column rather than a new table. A generic owner_type/owner_id
-- "stored_files" table can hold no foreign key - nothing would stop a row
-- pointing at a user that no longer exists - and it does not pay off later
-- either: issue attachments, when they arrive, will want a real FK to
-- issues(id) on a table the issue module owns, not a shared table read by
-- issue, comment and user alike (that would put a storage-adjacent module
-- in three modules' query paths, re-opening exactly the coupling the star
-- dependency graph exists to prevent). The reusable part is the storage
-- layer itself (shared.storage.ObjectStorage takes an arbitrary key prefix
-- and knows nothing about users); the reference from a user to their own
-- avatar is a 1:1-optional relation, which is a column.
--
-- The column is opaque: it holds whatever key ObjectStorage.put returned,
-- generated by the storage layer, never constructed or parsed here. No
-- CHECK constraint (V9 already removed the equivalent for the classification
-- enums) and no index (never queried by - lookups are always by user id).

ALTER TABLE "users" ADD COLUMN "avatar_object_key" varchar(255);
